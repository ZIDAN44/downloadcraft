//! `cargo xtask icons`: render DownloadCraft's app icon into `assets/app-icon/`.
//!
//! The icon is drawn here, from the geometry below, so it is DownloadCraft's own and every size
//! comes from one definition: a rounded blue square with a white arrow pointing down onto a tray.
//! Each pixel's coverage comes from signed distances (one sample per pixel, antialiased
//! analytically), so small sizes stay sharp without supersampling.
//!
//! Writes the hicolor PNGs (16–512 px, Linux and FreeBSD), a 1024 px master, an SVG of the same
//! drawing, `downloadcraft.ico` (Windows) and `downloadcraft.icns` (macOS). The outputs are
//! committed, so builds and packaging never run this.

use std::path::Path;

pub const ID: &str = "ai.storyteller.downloadcraft";
const HICOLOR: &[u32] = &[16, 24, 32, 48, 64, 128, 256, 512];
const ICO: &[u32] = &[16, 24, 32, 48, 64, 128, 256];

// Geometry, in units of the icon's side (0..1).
const MARGIN: f32 = 0.0625;
const RADIUS: f32 = 0.2;
/// The strokes: the arrow's shaft, its head, and the tray it points at.
const SHAFT: [(f32, f32); 2] = [(0.5, 0.24), (0.5, 0.60)];
const HEAD: [(f32, f32); 3] = [(0.33, 0.45), (0.5, 0.62), (0.67, 0.45)];
const TRAY: [(f32, f32); 2] = [(0.28, 0.76), (0.72, 0.76)];
const STROKE: f32 = 0.085;
// Colours: DownloadCraft blue (theme::APP_COLOR, #1F6FD6), lighter at the top.
const TOP: [f32; 3] = [0x3a as f32, 0x8a as f32, 0xee as f32];
const BOTTOM: [f32; 3] = [0x17 as f32, 0x58 as f32, 0xb4 as f32];

/// Distance from `p` to a rounded box centred at `c` with half-size `h` and corner radius `r`.
fn rounded_box(p: (f32, f32), c: (f32, f32), h: (f32, f32), r: f32) -> f32 {
    let qx = (p.0 - c.0).abs() - h.0 + r;
    let qy = (p.1 - c.1).abs() - h.1 + r;
    let outside = qx.max(0.0).hypot(qy.max(0.0));
    outside + qx.max(qy).min(0.0) - r
}

/// Distance from `p` to the segment `a`–`b`.
fn segment(p: (f32, f32), a: (f32, f32), b: (f32, f32)) -> f32 {
    let (px, py, bx, by) = (p.0 - a.0, p.1 - a.1, b.0 - a.0, b.1 - a.1);
    let t = ((px * bx + py * by) / (bx * bx + by * by)).clamp(0.0, 1.0);
    (px - bx * t).hypot(py - by * t)
}

/// Coverage (0..1) of a pixel whose centre is `d` (in pixels) from a shape's edge.
fn coverage(d: f32) -> f32 {
    (0.5 - d).clamp(0.0, 1.0)
}

/// Paint `src` with coverage `a` over the straight-alpha pixel `dst`.
fn over(dst: &mut [f32; 4], src: [f32; 3], a: f32) {
    let out_a = a + dst[3] * (1.0 - a);
    if out_a <= 0.0 {
        return;
    }
    for i in 0..3 {
        dst[i] = (src[i] * a + dst[i] * dst[3] * (1.0 - a)) / out_a;
    }
    dst[3] = out_a;
}

/// Distance to the white strokes (round caps and joins).
fn glyph(p: (f32, f32)) -> f32 {
    let d = segment(p, SHAFT[0], SHAFT[1]).min(segment(p, HEAD[0], HEAD[1])).min(segment(p, HEAD[1], HEAD[2]));
    d.min(segment(p, TRAY[0], TRAY[1]))
}

/// The icon at `size` × `size`, as straight-alpha RGBA bytes.
pub fn render(size: u32) -> Vec<u8> {
    let n = size as f32;
    let px = 1.0 / n;
    // At 16–24 px a proportional stroke would blur away; keep it at least ~1.6 px.
    let stroke = STROKE.max(1.6 * px);
    let mut out = Vec::with_capacity((size * size * 4) as usize);
    for y in 0..size {
        for x in 0..size {
            let p = ((x as f32 + 0.5) * px, (y as f32 + 0.5) * px);
            let mut c = [0.0f32; 4];
            let bg = coverage(rounded_box(p, (0.5, 0.5), (0.5 - MARGIN, 0.5 - MARGIN), RADIUS) * n);
            let t = ((p.1 - MARGIN) / (1.0 - 2.0 * MARGIN)).clamp(0.0, 1.0);
            let blue = [TOP[0] + (BOTTOM[0] - TOP[0]) * t, TOP[1] + (BOTTOM[1] - TOP[1]) * t, TOP[2] + (BOTTOM[2] - TOP[2]) * t];
            over(&mut c, blue, bg);
            over(&mut c, [255.0; 3], coverage((glyph(p) - stroke / 2.0) * n).min(bg));
            out.extend(c[..3].iter().map(|v| v.round().clamp(0.0, 255.0) as u8));
            out.push((c[3] * 255.0).round().clamp(0.0, 255.0) as u8);
        }
    }
    out
}

/// The same drawing as an SVG (hicolor `scalable`), on a 1024 canvas.
pub fn svg() -> String {
    let s = |v: f32| format!("{:.1}", v * 1024.0);
    let pt = |p: (f32, f32)| format!("{},{}", s(p.0), s(p.1));
    let hex = |c: [f32; 3]| format!("#{:02x}{:02x}{:02x}", c[0] as u8, c[1] as u8, c[2] as u8);
    format!(
        r##"<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <!-- DownloadCraft app icon. Generated by `cargo xtask icons` (xtask/src/icons.rs); edit there. -->
  <defs>
    <linearGradient id="blue" x1="0" y1="{m}" x2="0" y2="{m2}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="{top}"/>
      <stop offset="1" stop-color="{bottom}"/>
    </linearGradient>
  </defs>
  <rect x="{m}" y="{m}" width="{side}" height="{side}" rx="{rad}" fill="url(#blue)"/>
  <g fill="none" stroke="#ffffff" stroke-width="{sw}" stroke-linecap="round" stroke-linejoin="round">
    <polyline points="{s0} {s1}"/>
    <polyline points="{h0} {h1} {h2}"/>
    <polyline points="{t0} {t1}"/>
  </g>
</svg>
"##,
        m = s(MARGIN),
        m2 = s(1.0 - MARGIN),
        top = hex(TOP),
        bottom = hex(BOTTOM),
        side = s(1.0 - 2.0 * MARGIN),
        rad = s(RADIUS),
        sw = s(STROKE),
        s0 = pt(SHAFT[0]),
        s1 = pt(SHAFT[1]),
        h0 = pt(HEAD[0]),
        h1 = pt(HEAD[1]),
        h2 = pt(HEAD[2]),
        t0 = pt(TRAY[0]),
        t1 = pt(TRAY[1]),
    )
}

/// RGBA bytes as a PNG file.
pub fn png(size: u32, rgba: &[u8]) -> Result<Vec<u8>, String> {
    let mut out = Vec::new();
    let mut enc = png::Encoder::new(&mut out, size, size);
    enc.set_color(png::ColorType::Rgba);
    enc.set_depth(png::BitDepth::Eight);
    enc.set_compression(png::Compression::High);
    let mut w = enc.write_header().map_err(|e| format!("png: {e}"))?;
    w.write_image_data(rgba).map_err(|e| format!("png: {e}"))?;
    w.finish().map_err(|e| format!("png: {e}"))?;
    Ok(out)
}

/// An `.icns` file from PNGs keyed by pixel size. macOS reads PNG data in every entry type used here.
pub fn icns(pngs: &[(u32, Vec<u8>)]) -> Result<Vec<u8>, String> {
    // (entry type, pixel size): 1x and @2x variants of 16–512 pt.
    const TYPES: &[(&[u8; 4], u32)] = &[
        (b"icp4", 16),
        (b"ic11", 32),
        (b"icp5", 32),
        (b"ic12", 64),
        (b"ic07", 128),
        (b"ic13", 256),
        (b"ic08", 256),
        (b"ic14", 512),
        (b"ic09", 512),
        (b"ic10", 1024),
    ];
    let mut body = Vec::new();
    for (kind, size) in TYPES {
        let png = pngs.iter().find(|(s, _)| s == size).map(|(_, p)| p).ok_or(format!("icns: no {size} px image"))?;
        body.extend_from_slice(*kind);
        body.extend_from_slice(&u32::try_from(png.len() + 8).map_err(|_| "icns: image too large")?.to_be_bytes());
        body.extend_from_slice(png);
    }
    let mut out = b"icns".to_vec();
    out.extend_from_slice(&u32::try_from(body.len() + 8).map_err(|_| "icns: too large")?.to_be_bytes());
    out.extend_from_slice(&body);
    Ok(out)
}

fn write(path: &Path, bytes: &[u8]) -> Result<(), String> {
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir).map_err(|e| format!("create {}: {e}", dir.display()))?;
    }
    std::fs::write(path, bytes).map_err(|e| format!("write {}: {e}", path.display()))?;
    println!("wrote {}", path.display());
    Ok(())
}

pub fn run(root: &Path) -> Result<(), String> {
    let dir = root.join("assets").join("app-icon");
    let mut pngs: Vec<(u32, Vec<u8>)> = Vec::new();
    for size in HICOLOR.iter().copied().chain([1024]) {
        pngs.push((size, png(size, &render(size))?));
    }
    for (size, bytes) in &pngs {
        if *size == 1024 {
            write(&dir.join("downloadcraft-1024.png"), bytes)?;
        } else {
            write(&dir.join(format!("hicolor/{size}x{size}/apps/{ID}.png")), bytes)?;
        }
    }
    write(&dir.join(format!("hicolor/scalable/apps/{ID}.svg")), svg().as_bytes())?;
    let ico: Vec<Vec<u8>> = ICO.iter().filter_map(|s| pngs.iter().find(|(p, _)| p == s).map(|(_, b)| b.clone())).collect();
    write(&dir.join("downloadcraft.ico"), &crate::ico::pack(&ico)?)?;
    write(&dir.join("downloadcraft.icns"), &icns(&pngs)?)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn pixel(rgba: &[u8], size: u32, x: u32, y: u32) -> &[u8] {
        let i = ((y * size + x) * 4) as usize;
        &rgba[i..i + 4]
    }

    #[test]
    fn draws_a_blue_square_with_a_white_arrow() {
        let n = 256;
        let img = render(n);
        assert_eq!(img.len(), (n * n * 4) as usize);
        assert_eq!(pixel(&img, n, 0, 0)[3], 0);
        assert_eq!(pixel(&img, n, n - 1, n - 1)[3], 0);
        let bg = pixel(&img, n, n / 5, n / 2);
        assert_eq!(bg[3], 255);
        assert!(bg[2] > bg[1] && bg[1] > bg[0], "{bg:?}");
        // The shaft and the tray are white.
        assert_eq!(pixel(&img, n, n / 2, (n as f32 * 0.4) as u32), &[255, 255, 255, 255]);
        assert_eq!(pixel(&img, n, n / 2, (n as f32 * 0.76) as u32), &[255, 255, 255, 255]);
    }

    #[test]
    fn small_sizes_keep_the_arrow() {
        let n = 16;
        let img = render(n);
        let whitest = (4..10).map(|y| pixel(&img, n, 7, y)[0].min(pixel(&img, n, 8, y)[0])).max().unwrap_or(0);
        assert!(whitest > 200, "the arrow disappears at 16 px");
    }

    #[test]
    fn packs_icns_entries() {
        let pngs: Vec<(u32, Vec<u8>)> = [16, 32, 64, 128, 256, 512, 1024].iter().map(|&s| (s, vec![s as u8; 3])).collect();
        let f = icns(&pngs).unwrap();
        assert_eq!(&f[..4], b"icns");
        assert_eq!(u32::from_be_bytes(f[4..8].try_into().unwrap()) as usize, f.len());
        assert!(icns(&pngs[1..]).is_err());
    }

    #[test]
    fn svg_is_well_formed() {
        let s = svg();
        assert!(s.starts_with("<svg") && s.trim_end().ends_with("</svg>"));
        assert!(s.contains("#3a8aee"));
    }
}
